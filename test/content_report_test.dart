import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:vibe_craft/core/models/report_content_model.dart';
import 'package:vibe_craft/core/services/content_report_service.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('Content Report Model & Reason Tests', () {
    test('ReportReason enum has appropriate labels for Google Play compliance', () {
      expect(ReportReason.nsfwSexual.label, contains('Sexual or Inappropriate Content (NSFW)'));
      expect(ReportReason.violenceGore.label, contains('Violence, Gore'));
      expect(ReportReason.hateSpeech.label, contains('Hate Speech'));
      expect(ReportReason.selfHarmIllegal.label, contains('Self-Harm'));
      expect(ReportReason.copyrightInfringement.label, contains('Copyright'));
      expect(ReportReason.spamMisleading.label, contains('Spam'));
      expect(ReportReason.other.label, contains('Other'));
    });

    test('ContentReportModel serialization and deserialization', () {
      final now = DateTime.now();
      final report = ContentReportModel(
        contentId: 'ai_wall_123',
        contentType: 'ai_generated_wallpaper',
        contentUrlOrText: 'https://example.com/ai_wallpaper.jpg',
        reason: ReportReason.nsfwSexual.label,
        details: 'Offensive output generated by AI',
        reporterUserId: 'user_456',
        timestamp: now,
      );

      final map = report.toMap();
      expect(map['contentId'], equals('ai_wall_123'));
      expect(map['contentType'], equals('ai_generated_wallpaper'));
      expect(map['contentUrlOrText'], equals('https://example.com/ai_wallpaper.jpg'));
      expect(map['reason'], equals(ReportReason.nsfwSexual.label));
      expect(map['details'], equals('Offensive output generated by AI'));
      expect(map['reporterUserId'], equals('user_456'));
      expect(map['status'], equals('pending_review'));
      expect(map['appVersion'], equals('1.0.3+4'));

      final restored = ContentReportModel.fromMap(map, 'doc_789');
      expect(restored.id, equals('doc_789'));
      expect(restored.contentId, equals('ai_wall_123'));
      expect(restored.contentType, equals('ai_generated_wallpaper'));
      expect(restored.reason, equals(ReportReason.nsfwSexual.label));
    });
  });

  group('ContentReportService Local Caching & Blocking Tests', () {
    late SharedPreferences sharedPreferences;
    late ContentReportService service;

    setUp(() async {
      SharedPreferences.setMockInitialValues({});
      sharedPreferences = await SharedPreferences.getInstance();
      service = ContentReportServiceImpl(sharedPreferences: sharedPreferences);
    });

    test('isContentReported returns false initially and true after blocking', () async {
      const testContentId = 'ai_image_999';

      expect(service.isContentReported(testContentId), isFalse);

      await service.blockContentLocally(testContentId);

      expect(service.isContentReported(testContentId), isTrue);
      expect(service.getReportedContentIds(), contains(testContentId));
    });

    test('Multiple content IDs are cached uniquely', () async {
      await service.blockContentLocally('id_1');
      await service.blockContentLocally('id_2');
      await service.blockContentLocally('id_1'); // Duplicate

      final reported = service.getReportedContentIds();
      expect(reported.length, equals(2));
      expect(reported, containsAll(['id_1', 'id_2']));
    });
  });
}
